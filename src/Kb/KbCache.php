<?php

declare(strict_types=1);

namespace VitaGap\Kb;

use RuntimeException;

final class KbCache
{
    public const DEFAULT_CACHE_PATH = __DIR__ . '/../../var/kb_cache.php';
    public const DEFAULT_JSON_PATH = __DIR__ . '/../../kb/vitagap_kb.json';

    /**
     * Compile knowledge base array into high-speed PHP array cache.
     *
     * @param array<string, mixed> $data
     */
    public static function compile(array $data, string $cachePath = self::DEFAULT_CACHE_PATH): void
    {
        $dir = dirname($cachePath);
        if (!is_dir($dir) && !mkdir($dir, 0755, true) && !is_dir($dir)) {
            throw new RuntimeException("Failed to create cache directory: {$dir}");
        }

        $code = "<?php\n\ndeclare(strict_types=1);\n\n// Automatically generated by Vita-Gap KB compiler.\n// Do not edit directly.\n\nreturn " . var_export($data, true) . ";\n";
        
        $tempPath = $cachePath . '.' . bin2hex(random_bytes(4)) . '.tmp';
        if (file_put_contents($tempPath, $code, LOCK_EX) === false) {
            throw new RuntimeException("Failed to write temporary KB cache to {$tempPath}");
        }

        if (!rename($tempPath, $cachePath)) {
            @unlink($tempPath);
            throw new RuntimeException("Failed to move compiled KB cache to {$cachePath}");
        }
    }

    /**
     * Load KB array from cache if exists, otherwise from raw JSON.
     *
     * @return array<string, mixed>
     */
    public static function load(
        string $cachePath = self::DEFAULT_CACHE_PATH,
        string $jsonPath = self::DEFAULT_JSON_PATH
    ): array {
        if (file_exists($cachePath)) {
            $cached = require $cachePath;
            if (is_array($cached)) {
                return $cached;
            }
        }

        if (!file_exists($jsonPath)) {
            throw new RuntimeException("Knowledge base JSON not found at: {$jsonPath}");
        }

        $content = file_get_contents($jsonPath);
        if ($content === false) {
            throw new RuntimeException("Could not read KB JSON: {$jsonPath}");
        }

        $data = json_decode($content, true);
        if (!is_array($data)) {
            throw new RuntimeException("Invalid KB JSON format: " . json_last_error_msg());
        }

        // Attempt to compile cache for future requests
        try {
            self::compile($data, $cachePath);
        } catch (\Throwable) {
            // Ignore cache compilation errors during read-only runs
        }

        return $data;
    }
}
